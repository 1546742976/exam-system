import ts from 'typescript';
import path from 'node:path';
import {readFileSync,writeFileSync} from 'node:fs';
const config = ts.readConfigFile('tsconfig.json', ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, process.cwd());
const program = ts.createProgram(parsed.fileNames, parsed.options);
const all = ts.getPreEmitDiagnostics(program);
const owned = all.filter(d => !d.file || !d.file.fileName.replaceAll('\\','/').includes('/node_modules/'));
console.log(ts.formatDiagnosticsWithColorAndContext(owned,{getCurrentDirectory:()=>process.cwd(),getCanonicalFileName:f=>path.resolve(f),getNewLine:()=> '\n'}));
const upstream=all.filter(d=>!owned.includes(d)).map(d=>`${path.relative(process.cwd(),d.file.fileName).replaceAll('\\','/')}:${d.start}:${d.code}:${ts.flattenDiagnosticMessageText(d.messageText,' ')}`).sort();
const baselinePath='reports/typecheck-baseline.json';
if(process.argv.includes('--record-baseline'))writeFileSync(baselinePath,JSON.stringify(upstream,null,2)+'\n');
const baseline=new Set(JSON.parse(readFileSync(baselinePath,'utf8')));
const added=upstream.filter(d=>!baseline.has(d));
console.log(`Project diagnostics: ${owned.length}; upstream: ${upstream.length}; new upstream diagnostics: ${added.length}`);
for(const diagnostic of added)console.error(diagnostic);
process.exitCode = owned.length || added.length ? 1 : 0;
